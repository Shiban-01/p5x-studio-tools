import tkinter as tk
root = tk.Tk()
root.geometry("400x300")
lb1 = tk.Listbox(root)
lb1.pack()
for x in ["a","b","c"]: lb1.insert("end", x)
lb2 = tk.Listbox(root)
lb2.pack()
for x in ["x","y","z"]: lb2.insert("end", x)
root.update()
lb1.selection_set(1)
root.update()
print("lb1 sel inicial:", lb1.curselection(), "exportselection:", lb1.cget("exportselection"))
lb2.selection_set(2)
root.update()
print("lb1 sel tras seleccionar en lb2:", lb1.curselection())
root.destroy()